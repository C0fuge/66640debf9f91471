// Real App/virtualized thread/dialog over isolated synthetic CoreClient; no platform traffic.
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { join, resolve } from "node:path";
import { createRequire } from "node:module";
import { createServer } from "vite";
const { chromium } = createRequire(import.meta.url)("playwright-core");
const server = await createServer({ server: { host: "127.0.0.1", port: 53176, strictPort: false, open: false } });
const screenshotDir = process.env.CH_SCREENSHOT_DIR ? resolve(process.env.CH_SCREENSHOT_DIR) : null;
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ executablePath: process.env.CH_CHROMIUM, headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.route("**/src/main.tsx", route => route.fulfill({ contentType: "text/javascript", body: 'import "/tests/browser/pollFixture.tsx";' }));
  await page.goto(server.resolvedUrls.local[0]);
  const button = name => page.getByRole("button", { name, exact: true });
  const dialog = page.getByRole("dialog");
  const normal = () => page.locator(".poll-card").filter({ hasText: "Literal <question>" });
  const quiz = () => page.locator(".poll-card").filter({ hasText: "Unanswered quiz" });
  const calls = () => page.evaluate(() => window.pollFixture.calls());
  async function choose(account) {
    const accountButton = button(`${account}, Fixture, connected`);
    await accountButton.click();
    await page.getByRole("button").filter({ hasText: `${account} chat` }).click();
    await page.getByRole("heading", { name: `${account} chat`, exact: true }).waitFor();
    assert.equal(await accountButton.getAttribute("aria-pressed"), "true");
  }
  async function screenshot(name) {
    if (!screenshotDir) return;
    await mkdir(screenshotDir, { recursive: true });
    await page.screenshot({ path: join(screenshotDir, name), fullPage: true });
  }
  await choose("Alpha");
  await normal().getByRole("button", { name: "Open poll" }).click();
  await screenshot("poll-panel.png");
  assert.deepEqual(await calls(), [], "opening and rendering never votes or refreshes");
  assert.equal(await dialog.getByRole("button", { name: "Close poll", exact: true }).isDisabled(), true);
  await dialog.getByRole("button", { name: "Refresh poll", exact: true }).click();
  await dialog.getByLabel("First <answer>", { exact: false }).check();
  assert.deepEqual((await calls()).map(call => call.method), ["refreshPoll"], "selection is local until explicit submission");
  await page.evaluate(() => window.pollFixture.next("unknown"));
  await dialog.getByRole("button", { name: "Submit vote", exact: true }).click();
  await dialog.getByText(/may have completed/).waitFor();
  await screenshot("poll-outcome-unknown.png");
  assert.equal(await dialog.getByRole("button", { name: "Submit vote", exact: true }).isDisabled(), true);
  assert.equal(await dialog.getByRole("button", { name: "Close poll", exact: true }).isDisabled(), true);
  await dialog.getByRole("button", { name: "Close panel", exact: true }).click();
  await choose("Beta");
  await normal().getByRole("button", { name: "Open poll" }).click();
  assert.equal(await dialog.getByRole("button", { name: "Close poll", exact: true }).isDisabled(), true);
  await dialog.getByRole("button", { name: "Close panel", exact: true }).click();
  await choose("Alpha");
  await normal().getByRole("button", { name: "Open poll" }).click();
  assert.equal(await dialog.getByRole("button", { name: "Close poll", exact: true }).isDisabled(), true, "account remount cannot release uncertain target");
  assert.deepEqual((await calls()).map(call => call.method), ["refreshPoll", "votePoll"], "switching and reopening never reads or replays automatically");
  await page.evaluate(() => window.pollFixture.next("missing"));
  await dialog.getByRole("button", { name: "Refresh poll", exact: true }).click();
  await dialog.getByText(/Current poll state was not returned/).waitFor();
  assert.equal(await dialog.getByRole("button", { name: "Close poll", exact: true }).isDisabled(), true);
  await dialog.getByRole("button", { name: "Refresh poll", exact: true }).click();
  await dialog.getByRole("button", { name: "Retract vote", exact: true }).waitFor();
  await dialog.getByRole("button", { name: "Retract vote", exact: true }).click();
  await dialog.getByRole("button", { name: "Close poll", exact: true }).click();
  await dialog.getByText(/Public voting · Closed/).waitFor();
  await screenshot("poll-closed.png");
  await dialog.getByRole("button", { name: "Close panel", exact: true }).click();
  await quiz().getByRole("button", { name: "Open poll" }).click();
  await dialog.getByText("Your current choice is unknown.", { exact: true }).waitFor();
  await dialog.getByRole("button", { name: "Refresh poll", exact: true }).click();
  await dialog.getByText("Review the reported poll before another action.", { exact: true }).waitFor();
  assert.equal(await dialog.getByRole("button", { name: "Submit vote", exact: true }).isDisabled(), true, "a sparse targeted read cannot invent a negative quiz choice");
  assert.equal(await dialog.getByRole("button", { name: "Retract vote", exact: true }).count(), 0);
  await dialog.getByRole("button", { name: "Close panel", exact: true }).click();
  const sent = await calls();
  assert.deepEqual(sent.map(call => call.method), ["refreshPoll", "votePoll", "refreshPoll", "refreshPoll", "votePoll", "closePoll", "refreshPoll"]);
  assert.deepEqual(sent[1].params, { thread: { accountId: "Alpha", chatId: "chat", topicId: "topic-1" }, messageId: "older", optionIds: ["b:AA"] });
  assert.deepEqual(sent[4].params.optionIds, []);
  assert.equal(await page.locator("script").filter({ hasText: "Literal" }).count(), 0);
  assert.equal(await button("Create poll").count(), 0);
  // A late Beta response cannot replace Alpha's new panel.
  await choose("Beta");
  await normal().getByRole("button", { name: "Open poll" }).click();
  await page.evaluate(() => window.pollFixture.next("hold"));
  await dialog.getByRole("button", { name: "Refresh poll", exact: true }).click();
  await page.evaluate(() => document.querySelector("dialog").close());
  await choose("Alpha");
  await quiz().getByRole("button", { name: "Open poll" }).click();
  await page.evaluate(() => window.pollFixture.release());
  await dialog.getByRole("heading", { name: "Unanswered quiz", exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log("Poll display, explicit writes, uncertainty recovery, sparse quiz and account scope passed");
} finally { await browser?.close(); await server.close(); }
