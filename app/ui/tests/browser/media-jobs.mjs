// Remote Chromium only. Real App/ThreadPane; all accounts, jobs and copies are synthetic.
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";
import { createServer } from "vite";
const { chromium } = createRequire(import.meta.url)("playwright-core");
const server = await createServer({ server: { host: "127.0.0.1", port: 53178, strictPort: false, open: false } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ executablePath: process.env.CH_CHROMIUM, headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
  const errors = [];
  page.on("pageerror", error => errors.push(error.name + ": " + error.message));
  await page.route("**/src/main.tsx", route => route.fulfill({ contentType: "text/javascript", body: 'import "/tests/browser/mediaJobsFixture.tsx";' }));
  await page.goto(server.resolvedUrls.local[0]);
  const choose = async account => {
    await page.getByRole("button", { name: `${account}, Fixture, connected`, exact: true }).click();
    await page.getByRole("button").filter({ hasText: `${account} attachments` }).click();
    await page.getByRole("heading", { name: `${account} attachments`, exact: true }).waitFor();
    await page.getByText(`${account} download caption`, { exact: true }).waitFor();
  };
  const bubble = account => page.getByRole("article").filter({ hasText: `${account} download caption` });
  const panel = () => page.getByRole("dialog");
  const close = () => panel().getByRole("button", { name: "Close panel", exact: true }).click();
  const starts = () => page.evaluate(() => window.mediaJobsFixture.requests().filter(request => request.method.startsWith("startMedia")));
  const openAttachment = async account => {
    const reveal = bubble(account).getByRole("button", { name: "Reveal attachment details", exact: true });
    if (await reveal.count()) await reveal.click();
    await bubble(account).getByRole("button", { name: "Attachment actions", exact: true }).click();
    await panel().getByRole("button", { name: "Latest jobs", exact: true }).waitFor();
    await page.waitForFunction(() => [...document.querySelectorAll("dialog button")].some(button => button.textContent === "Latest jobs" && !button.disabled));
  };
  const capture = async name => {
    if (!process.env.CH_SCREENSHOT_DIR) return;
    await page.evaluate(async () => {
      await document.fonts.ready;
      let previous = "", stable = 0, snapshot;
      const deadline = performance.now() + 5000;
      while (performance.now() < deadline) {
        await new Promise(resolve => requestAnimationFrame(resolve));
        snapshot = [...document.querySelectorAll(".thread-row[data-index]")].sort((a,b) => Number(a.dataset.index) - Number(b.dataset.index))
          .map(row => { const bounds = row.getBoundingClientRect(); return [bounds.top, bounds.bottom]; });
        const valid = snapshot.length === 4 && snapshot.every(([top,bottom], i) => bottom > top && (!i || top >= snapshot[i-1][1] - 0.5));
        const next = JSON.stringify(snapshot);
        stable = valid ? (next === previous ? stable + 1 : 1) : 0; previous = next;
        if (stable >= 3) return;
      }
      throw Error("Attachment action rows did not settle without overlap: " + JSON.stringify(snapshot));
    });
    await panel().evaluate(element => { element.scrollTop = 0; });
    const directory = resolve(process.env.CH_SCREENSHOT_DIR);
    await mkdir(directory, { recursive: true });
    await page.screenshot({ path: join(directory, name), fullPage: true });
  };
  await choose("Alpha");
  assert.equal(await bubble("Alpha").getByRole("button", { name: "Attachment actions", exact: true }).count(), 0, "spoiler actions are withheld before reveal");
  assert.equal(await page.getByRole("article").filter({ hasText: "Pending attachment" }).getByRole("button").count(), 0);
  assert.deepEqual(await starts(), [], "mounting and reading history never starts a download");
  await openAttachment("Alpha");
  await panel().getByText("No jobs in this page.", { exact: true }).waitFor({ state: "hidden" });
  await panel().getByRole("button", { name: "Earlier jobs", exact: true }).waitFor();
  assert.equal(await panel().getByRole("button", { name: "Save a new copy", exact: true }).count(), 0, "browser provider false hides Save");
  assert.equal((await starts()).length, 0);
  await panel().getByRole("button", { name: "Download attachment", exact: true }).click();
  await page.waitForFunction(() => window.mediaJobsFixture.requests().some(request => request.method === "startMediaDownload"));
  const original = (await starts())[0].params;
  assert.deepEqual(original.thread, { accountId: "Alpha", chatId: "same-chat", topicId: "42" });
  assert.equal(original.sessionId, "fixture-session"); assert.match(original.requestKey, /^[A-Za-z0-9_-]{1,64}$/);
  assert.deepEqual(Object.keys(original).sort(), ["messageId", "requestKey", "sessionId", "thread"]);
  await close();
  await choose("Beta");
  await page.evaluate(() => window.mediaJobsFixture.loseFirst());
  await openAttachment("Beta");
  await panel().getByText("No jobs in this page.", { exact: true }).waitFor();
  assert.equal(await panel().locator("[data-job-id^=Alpha]").count(), 0, "same IDs in another account do not acquire late results");
  assert.equal((await starts()).length, 1);
  await close();
  await choose("Alpha");
  await openAttachment("Alpha");
  await panel().getByRole("button", { name: "Recover request", exact: true }).click();
  await panel().getByText(/No receipt has appeared/).waitFor();
  assert.equal(await panel().getByRole("button", { name: "Download attachment", exact: true }).isDisabled(), true);
  await page.evaluate(() => window.mediaJobsFixture.admitFirst());
  await panel().getByRole("button", { name: "Recover request", exact: true }).click();
  await panel().getByText("Recovered the existing job. No operation was restarted.", { exact: true }).waitFor();
  await panel().locator("[data-job-id=Alpha-new-1]").getByText("Downloading", { exact: true }).waitFor();
  assert.equal((await starts()).length, 1, "same-key recovery never submits another start");
  await capture("attachment-jobs-download.png");
  await page.evaluate(() => { window.mediaJobsFixture.finishDownload(); window.mediaJobsFixture.provider(true); });
  await panel().getByRole("button", { name: "Save a new copy", exact: true }).waitFor();
  await panel().getByRole("button", { name: "Save a new copy", exact: true }).click();
  const saving = panel().locator("[data-job-id=Alpha-new-2]");
  await saving.getByText("Choosing destination", { exact: true }).waitFor();
  assert.match(await panel().textContent(), /existing files will not be replaced/);
  await saving.getByRole("button", { name: "Cancel job", exact: true }).click();
  await saving.getByText("Cancellation requested; waiting for completion", { exact: true }).waitFor();
  assert.equal(await panel().getByRole("button", { name: "Save a new copy", exact: true }).isDisabled(), true);
  await capture("attachment-jobs-cancelling.png");
  await page.evaluate(() => window.mediaJobsFixture.settleChooser());
  await saving.getByText("Cancelled", { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => window.mediaJobsFixture.copies()), 0, "late chooser completion after cancellation cannot become a copy");
  await page.evaluate(() => window.mediaJobsFixture.offline());
  await panel().getByRole("button", { name: "Save a new copy", exact: true }).click();
  await panel().locator("[data-job-id=Alpha-new-3]").getByText("Choosing destination", { exact: true }).waitFor();
  assert.equal(await panel().getByRole("button", { name: "Download attachment", exact: true }).isDisabled(), true);
  await page.evaluate(() => window.mediaJobsFixture.settleChooser());
  await panel().locator("[data-job-id=Alpha-new-3]").getByText("Saved a new copy", { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => window.mediaJobsFixture.copies()), 1);
  await capture("attachment-jobs-save-copy.png");
  const writes = await starts();
  assert.equal(writes.length, 3); assert.notEqual(writes[1].params.requestKey, writes[2].params.requestKey);
  await page.evaluate(() => { window.mediaJobsFixture.deleteTarget(); window.mediaJobsFixture.reset(); });
  await panel().getByText(/The attachment changed/).waitFor();
  await close();
  await page.getByRole("button", { name: "Attachment jobs", exact: true }).click();
  await panel().getByLabel("Job scope").selectOption({ label: "Topic 42" });
  await panel().getByRole("button", { name: "Earlier jobs", exact: true }).click();
  const deletedJob = panel().locator("[data-job-id=Alpha-old-1]");
  await deletedJob.getByRole("button", { name: "Cancel job", exact: true }).click();
  await deletedJob.getByText("Cancelled", { exact: true }).waitFor();
  assert.equal((await starts()).length, 3, "delete/reset, paging and recovery do not replay jobs");
  await close();
  const left = await page.locator(".thread-bubble").evaluateAll(rows => rows.map(row => Math.round(row.getBoundingClientRect().left)));
  assert.equal(new Set(left).size, 1, "incoming and outgoing bubbles stay left aligned");
  assert.equal(await page.locator("a[href^='file:'], img, iframe").count(), 0);
  assert.deepEqual(errors, []);
  console.log("Explicit attachment jobs, scoped recovery, native-provider gate and late cancellation passed Chromium checks.");
} finally { await browser?.close(); await server.close(); }
