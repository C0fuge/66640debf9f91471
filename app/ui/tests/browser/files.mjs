// Run only in remote Chromium against typed synthetic receipts.
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";
import { createServer } from "vite";
const { chromium } = createRequire(import.meta.url)("playwright-core");
const server = await createServer({ server: { host: "127.0.0.1", port: 53181, strictPort: false, open: false } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ executablePath: process.env.CH_CHROMIUM, headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
  const errors = []; page.on("pageerror", e => errors.push(e.name + ": " + e.message));
  await page.route("**/src/main.tsx", route => route.fulfill({ contentType: "text/javascript", body: 'import "/tests/browser/fileFixture.tsx";' }));
  await page.goto(server.resolvedUrls.local[0]);
  const chooseChat = async account => {
    await page.getByRole("button", { name: `${account}, Fixture, connected`, exact: true }).click();
    await page.getByRole("button").filter({ hasText: `${account} files` }).click();
    await page.getByRole("heading", { name: `${account} files`, exact: true }).waitFor();
  };
  const files = () => page.getByLabel("Files for this conversation", { exact: true });
  const count = method => page.evaluate(m => window.fileFixture.requests().filter(r => r.method === m).length, method);
  const snapshot = async name => {
    if (!process.env.CH_SCREENSHOT_DIR) return;
    await page.evaluate(() => document.fonts.ready);
    const dir = resolve(process.env.CH_SCREENSHOT_DIR); await mkdir(dir, { recursive: true });
    await page.screenshot({ path: join(dir, name), fullPage: true });
  };
  await chooseChat("Alpha");
  await page.getByLabel("Message", { exact: true }).fill("Preserve this text draft");
  assert.equal(await count("startFileSelection"), 0); assert.equal(await count("enqueueFile"), 0);
  await page.getByRole("button", { name: "Choose file", exact: true }).click();
  await files().getByText("Copying file…", { exact: true }).waitFor();
  assert.match(await files().textContent(), /Copied 3 bytes of 12 bytes/);
  await page.getByRole("button").filter({ hasText: /^Outbox/ }).click();
  assert.match(await page.getByLabel("Message outbox").textContent(), /Uploaded 5 bytes of 12/);
  assert.equal(await page.getByRole("button", { name: "Retry", exact: true }).count(), 0, "failed files have no retry control");
  await page.evaluate(() => window.fileFixture.ready("Alpha"));
  await files().getByLabel("File caption", { exact: true }).fill(" literal file caption ");
  assert.equal(await count("enqueueFile"), 0, "review and options are local only");
  assert.equal(await files().locator("report").count(), 0, "filename remains escaped text");
  assert.equal(await files().getByText("The connection is unavailable.", { exact: true }).count(), 0, "a recovered receipt clears the stale transport notice");
  await snapshot("files-ready-review.png");
  await files().getByRole("button", { name: "Send file", exact: true }).click();
  await files().getByText("Admission unconfirmed", { exact: true }).waitFor();
  assert.match(await files().textContent(), /sending again could duplicate/i);
  assert.equal(await count("enqueueFile"), 1);
  assert.equal(await page.getByLabel("Message", { exact: true }).inputValue(), "Preserve this text draft");
  await files().getByRole("button", { name: "Reload file status", exact: true }).click();
  assert.equal(await count("enqueueFile"), 1);
  assert.equal(await files().getByRole("button", { name: "Send file", exact: true }).count(), 0);
  await snapshot("files-admission-unknown.png");
  await page.evaluate(() => window.fileFixture.mode("consumed"));
  await page.getByRole("button", { name: "Choose file", exact: true }).click();
  await page.evaluate(() => window.fileFixture.ready("Alpha"));
  await files().getByRole("button", { name: "Send file", exact: true }).click();
  await files().getByText("Added to outbox. Delivery record unavailable.", { exact: true }).waitFor();
  assert.equal(await count("enqueueFile"), 2);
  await chooseChat("Beta"); await page.evaluate(() => window.fileFixture.hold());
  await page.getByRole("button", { name: "Choose file", exact: true }).click();
  await chooseChat("Alpha"); await page.evaluate(() => window.fileFixture.release());
  await page.getByRole("button").filter({ hasText: /^Files/ }).click();
  assert.equal(await files().getByText("Ready to send", { exact: true }).count(), 0, "late Beta receipt cannot enter Alpha");
  await page.getByRole("button", { name: "Choose file", exact: true }).click();
  await files().getByText("Copying file…", { exact: true }).waitFor();
  await page.evaluate(() => { window.fileFixture.ready("Alpha"); window.fileFixture.capacity(); });
  await files().getByText(/Sent files are retained/).waitFor();
  await snapshot("files-retained-capacity.png");
  assert.equal(await count("enqueueFile"), 2);
  await page.setViewportSize({ width: 390, height: 844 });
  await snapshot("files-retained-capacity-mobile.png");
  assert.equal(await page.getByLabel("Message", { exact: true }).inputValue(), "Preserve this text draft");
  const bounds = await page.getByLabel("Message", { exact: true }).boundingBox();
  assert.ok(bounds && bounds.y >= 0 && bounds.y + bounds.height <= 844, "message draft stays inside the mobile viewport");
  assert.deepEqual(errors, []);
  console.log("File composer passed Chromium checks.");
} finally { await browser?.close(); await server.close(); }
