"""Generate the typed modules of contact_hub_sdk from ../../schemas.

    python tools/gen_types.py            # rewrite the generated modules
    python tools/gen_types.py --check    # exit 1 if they drifted from schemas/

Generated (do not edit by hand): types.py, capabilities.py, registry.py, _emitters.py.
tests/test_generated.py runs --check, so a schema change without regeneration fails CI.
"""

from __future__ import annotations

import json
import keyword
import posixpath
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCHEMAS = HERE.parent.parent.parent / "schemas"
PKG = HERE.parent / "src" / "contact_hub_sdk"

HEADER = '"""GENERATED by tools/gen_types.py from schemas/. Do not edit."""\n\n'

# Primitive $defs: (file, def) -> Python annotation.
PRIMITIVES = {
    ("common.json", "Timestamp"): "datetime",
    ("jsonrpc.json", "RequestId"): "int | str",
    ("common.json", "Ext"): "dict[str, dict[str, Any]]",
    ("common.json", "IdList"): "list[str]",
    ("capabilities.json", "Capabilities"): "dict[str, Any]",
}


def load_all() -> dict[str, dict]:
    out = {}
    for p in sorted(SCHEMAS.rglob("*.json")):
        rel = p.relative_to(SCHEMAS).as_posix()
        if rel.startswith("examples/"):
            continue
        out[rel] = json.loads(p.read_text())
    return out


DOCS = load_all()
EVENT_NAMES = DOCS["events.json"]["$defs"]["EventName"]["enum"]


def resolve(file: str, ref: str) -> tuple[str, str]:
    path, _, frag = ref.partition("#")
    target = posixpath.normpath(posixpath.join(posixpath.dirname(file), path)) if path else file
    if not frag:
        return target, "<root>"
    assert frag.startswith("/$defs/"), ref
    return target, frag[len("/$defs/") :]


def get_def(file: str, name: str) -> dict:
    doc = DOCS[file]
    return doc if name == "<root>" else doc["$defs"][name]


def pascal(s: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in s.replace(".", "_").split("_") if p)


def py_name(file: str, name: str) -> str:
    if name == "<root>":
        return pascal(posixpath.basename(file)[:-5])
    if file == "events.json" and name in EVENT_NAMES:
        return pascal(name) + "Event"
    return pascal(name) if "." in name else name


def kind_of(file: str, name: str) -> str:
    """'prim' | 'enum' | 'alias' | 'object' | 'skip'."""
    if (file, name) in PRIMITIVES:
        return "prim"
    s = get_def(file, name)
    if "enum" in s and s.get("type") == "string":
        return "enum"
    if set(s) - {"description", "$ref"} == set() and "$ref" in s:
        return "alias"
    if s.get("type") == "object" or "properties" in s or "allOf" in s or "oneOf" in s:
        return "object"
    if s.get("type") in ("string", "integer"):
        return "prim"
    return "skip"


def prim_type(file: str, name: str) -> str:
    if (file, name) in PRIMITIVES:
        return PRIMITIVES[(file, name)]
    s = get_def(file, name)
    if "$ref" in s:
        return prim_type(*resolve(file, s["$ref"]))
    return {"string": "str", "integer": "int"}[s["type"]]


class Gen:
    def __init__(self, module_defs: set[tuple[str, str]]):
        self.module_defs = module_defs  # defs emitted in this module
        self.imports: set[tuple[str, str]] = set()  # (module, name) cross-module refs

    def ref_type(self, file: str, ref: str) -> str:
        tf, tn = resolve(file, ref)
        k = kind_of(tf, tn)
        if k == "prim":
            return prim_type(tf, tn)
        if k == "alias":
            return self.ref_type(tf, get_def(tf, tn)["$ref"])
        if k == "enum":
            return f"{py_name(tf, tn)} | str"
        if k == "object":
            s = get_def(tf, tn)
            if not s.get("properties") and not s.get("allOf") and not s.get("oneOf"):
                return "dict[str, Any]" if tn != "Empty" else "Empty"
            return py_name(tf, tn)
        raise ValueError(f"cannot type {ref} from {file}")

    def prop_type(self, file: str, ps: dict) -> tuple[str, bool]:
        """(annotation without None, nullable)."""
        if "$ref" in ps:
            return self.ref_type(file, ps["$ref"]), False
        if "anyOf" in ps:
            alts = [a for a in ps["anyOf"] if a != {"type": "null"}]
            assert len(alts) == 1 and len(ps["anyOf"]) == 2, ps
            t, _ = self.prop_type(file, alts[0])
            return t, True
        if "oneOf" in ps:
            alts = [self.prop_type(file, a)[0] for a in ps["oneOf"]]
            return " | ".join(dict.fromkeys(alts)), False
        if "const" in ps:
            return type(ps["const"]).__name__, True  # a const flag is either that value or absent
        t = ps.get("type")
        nullable = False
        if isinstance(t, list):
            nullable = "null" in t
            rest = [x for x in t if x != "null"]
            assert len(rest) == 1, ps
            t = rest[0]
        if t == "array":
            it, _ = self.prop_type(file, ps["items"])
            return f"list[{it}]", nullable
        if t == "object":
            assert "properties" not in ps, ps
            ap = ps.get("additionalProperties")
            if isinstance(ap, dict) and ap.get("type") in ("string", "boolean"):
                return f"dict[str, {'str' if ap['type'] == 'string' else 'bool'}]", nullable
            return "dict[str, Any]", nullable
        return {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}[t], nullable

    def collect_props(self, file: str, s: dict) -> tuple[dict[str, tuple[str, dict]], set[str]]:
        props: dict[str, tuple[str, dict]] = {}
        req: set[str] = set()
        for base in s.get("allOf", []):
            if "$ref" in base:
                bf, bn = resolve(file, base["$ref"])
                bp, br = self.collect_props(bf, get_def(bf, bn))
                props.update(bp)
                req |= br
        for name, ps in s.get("properties", {}).items():
            props[name] = (file, ps)
        req |= set(s.get("required", []))
        # ReactionKey-style "exactly one of": every branch's properties become optional fields.
        for alt in s.get("oneOf", []):
            for name, ps in alt.get("properties", {}).items():
                props.setdefault(name, (file, ps))
        return props, req

    def dataclass(self, file: str, name: str, all_optional: bool = False) -> str:
        s = get_def(file, name)
        cls = py_name(file, name)
        props, req = self.collect_props(file, s)
        doc = s.get("description") or s.get("title") or f"{name} ({file})."
        lines = ["@dataclass(kw_only=True, slots=True)", f"class {cls}:", f'    """{doc.strip()}"""', ""]
        if not props:
            lines.append("    pass")
        for pname, (pfile, ps) in props.items():
            t, nullable = self.prop_type(pfile, ps)
            attr = pname + "_" if keyword.iskeyword(pname) else pname
            assert attr == pname, f"keyword field {pname} in {cls}"
            if pname in req and not all_optional:
                lines.append(f"    {pname}: {t}")
            elif not nullable and t in ("bool", "int") and not all_optional and "default" in ps:
                lines.append(f"    {pname}: {t} = {ps['default']!r}")
            elif not nullable and t == "bool" and not all_optional:
                lines.append(f"    {pname}: {t} = False")  # spec 8.4: non-nullable booleans default false
            else:
                lines.append(f"    {pname}: {t} | None = None")
        return "\n".join(lines) + "\n"

    def enum(self, file: str, name: str) -> str:
        s = get_def(file, name)
        cls = py_name(file, name)
        doc = s.get("description") or f"{name} ({file}). Unknown wire values are kept as plain str."
        lines = [f"class {cls}(StrEnum):", f'    """{doc.strip()}"""', ""]
        for v in s["enum"]:
            ident = v.upper().replace(".", "_").replace("-", "_")
            if ident[0].isdigit() or keyword.iskeyword(ident):
                ident = "V_" + ident
            lines.append(f"    {ident} = {v!r}")
        return "\n".join(lines) + "\n"


def types_module() -> str:
    defs: list[tuple[str, str]] = []
    for file in sorted(DOCS):
        if file in ("errors.json", "jsonrpc.json", "capabilities.json") or file.endswith("registry.json"):
            continue
        doc = DOCS[file]
        if "properties" in doc:
            defs.append((file, "<root>"))
        for name in doc.get("$defs", {}):
            defs.append((file, name))
    defs.append(("jsonrpc.json", "CancelParams"))
    g = Gen(set(defs))
    enums, classes, aliases, names = [], [], [], {}
    for file, name in defs:
        k = kind_of(file, name)
        if k in ("prim", "skip"):
            continue
        cls = py_name(file, name)
        if k == "object":
            s = get_def(file, name)
            if not s.get("properties") and not s.get("allOf") and not s.get("oneOf") and name != "Empty":
                aliases.append(f"{cls} = Empty")
                names[cls] = (file, name)
                continue
        if cls in names:
            raise SystemExit(f"name clash: {cls} from {file}#{name} and {names[cls]}")
        names[cls] = (file, name)
        if k == "enum":
            enums.append(g.enum(file, name))
        elif k == "object":
            classes.append(g.dataclass(file, name))
        elif k == "alias":
            target = g.ref_type(file, get_def(file, name)["$ref"])
            aliases.append(f"{cls} = {target}")
    body = (
        HEADER
        + "from __future__ import annotations\n\n"
        + "from dataclasses import dataclass\nfrom datetime import datetime\nfrom enum import StrEnum\nfrom typing import Any\n\n"
        + "__all__ = [\n"
        + "".join(f"    {n!r},\n" for n in sorted(names))
        + "]\n\n\n"
        + "\n\n".join(enums)
        + "\n\n"
        + "\n\n".join(classes)
        + "\n\n"
        + "\n".join(aliases)
        + "\n"
    )
    return body


def capabilities_module() -> str:
    doc = DOCS["capabilities.json"]
    g = Gen(set())
    keys = doc["$defs"]["CapabilityKey"]["enum"]
    caps = doc["$defs"]["Capabilities"]["properties"]
    classes, param_of = [], {}
    for name, s in doc["$defs"].items():
        if name.endswith("Params"):
            classes.append(g.dataclass("capabilities.json", name, all_optional=True))
    for key, ps in caps.items():
        for alt in ps.get("oneOf", []):
            if "$ref" in alt:
                param_of[key] = resolve("capabilities.json", alt["$ref"])[1]
    defaults = {}
    for name, s in doc["$defs"].items():
        if name.endswith("Params"):
            defaults[name] = {p: v["default"] for p, v in s.get("properties", {}).items() if "default" in v}
    return (
        HEADER
        + "from __future__ import annotations\n\n"
        + "from dataclasses import dataclass\nfrom typing import Any\n\n"
        + "from .types import *  # noqa: F403  (enum names used in the annotations below)\n\n"
        + "#: Every capability key defined by API v1 (spec section 14.3).\n"
        + f"CAPABILITY_KEYS: tuple[str, ...] = {tuple(keys)!r}\n\n"
        + "#: Capability key -> name of its parameter class (keys not listed take only `true`).\n"
        + f"PARAMS_OF: dict[str, str] = {param_of!r}\n\n"
        + "#: Parameter defaults per parameter class, as the schema states them.\n"
        + f"DEFAULTS: dict[str, dict[str, Any]] = {defaults!r}\n\n\n"
        + "\n\n".join(classes)
    )


def registry_module() -> str:
    reg = DOCS["methods/registry.json"]
    methods = []
    for m in reg["methods"]:
        file = "methods/" + m["schema"]
        defs = DOCS[file]["$defs"]
        g = Gen(set())

        def tname(suffix: str) -> str:
            key = f"{m['name']}.{suffix}"
            if key not in defs:
                return "None"
            return py_name(file, key)

        gates = "".join(
            f"GatedParam({g['param']!r}, {g['capability']!r}"
            + (f", {g['equals']!r}" if "equals" in g else "")
            + "),"
            for g in m.get("gated_params", [])
        ).replace("),G", "), G")
        methods.append(
            f"    {m['name']!r}: MethodInfo({m['name']!r}, {m['direction']!r}, {m['capability']!r}, "
            f"{m.get('timeout_seconds', reg['default_timeout_seconds'])}, {bool(m.get('progress', False))}, "
            f"T.{tname('params')}, T.{tname('result')}, {m['schema']!r}, ({gates})),"
        )
        del g
    events = [f"    {e!r}: T.{py_name('events.json', e)}," for e in reg["events"]]
    return (
        HEADER
        + "from __future__ import annotations\n\n"
        + "from collections.abc import Callable\nfrom dataclasses import dataclass\nfrom typing import Any\n\n"
        + "from . import types as T\n\n"
        + f"API_VERSION = {reg['api_version']!r}\n"
        + f"CANCEL_METHOD = {reg.get('cancel', '$/cancelRequest')!r}\n"
        + "#: Timeout for requests without their own, both directions (spec 4.6, 12).\n"
        + f"DEFAULT_TIMEOUT_SECONDS = {reg['default_timeout_seconds']!r}\n\n\n"
        + "@dataclass(frozen=True, slots=True)\n"
        + "class GatedParam:\n"
        + '    """A parameter that needs a capability (spec 14.2). ``param`` is a dotted path; a\n'
        + "    ``[]`` segment means any array element. It is present when the value there is not\n"
        + '    absent and not ``null`` and, if ``equals`` is set, equals it."""\n\n'
        + "    param: str\n    capability: str\n    equals: Any = None\n\n"
        + "    def is_present_in(self, params: Any) -> bool:\n"
        + "        def walk(v: Any, segs: list[str]) -> bool:\n"
        + "            if not segs:\n"
        + "                if v is None:\n                    return False\n"
        + "                e = self.equals\n"
        + "                return e is None or (type(v) is type(e) and v == e)\n"
        + "            seg, rest = segs[0], segs[1:]\n"
        + "            each = seg.endswith('[]')\n"
        + "            key = seg[:-2] if each else seg\n"
        + "            if not isinstance(v, dict) or key not in v:\n                return False\n"
        + "            child = v[key]\n"
        + "            if each:\n"
        + "                return isinstance(child, list) and any(walk(item, rest) for item in child)\n"
        + "            return walk(child, rest)\n\n"
        + "        return walk(params, self.param.split('.'))\n\n\n"
        + "@dataclass(frozen=True, slots=True)\n"
        + "class MethodInfo:\n"
        + '    """One row of schemas/methods/registry.json."""\n\n'
        + "    name: str\n    direction: str  # 'core_to_plugin' | 'plugin_to_core'\n"
        + "    capability: str  # a capability key, or 'required'\n"
        + "    timeout_seconds: int  # spec 4.6; DEFAULT_TIMEOUT_SECONDS where the registry gives none\n"
        + "    progress: bool  # emits transfer.progress, which resets the timeout\n"
        + "    params: type[Any]\n    result: type[Any]\n"
        + "    schema: str  # the file under schemas/methods/ that defines params and result\n"
        + "    gated_params: tuple[GatedParam, ...] = ()\n\n"
        + "    def missing_capabilities(self, params: Any, has: Callable[[str], bool]) -> list[GatedParam]:\n"
        + '        """The gated parameters present in ``params`` whose capability ``has`` denies, in\n'
        + '        table order: each is a reason to answer ``NOT_SUPPORTED`` (spec 14.2)."""\n'
        + "        return [g for g in self.gated_params if g.is_present_in(params) and not has(g.capability)]\n\n\n"
        + "METHODS: dict[str, MethodInfo] = {\n"
        + "\n".join(methods)
        + "\n}\n\n"
        + "#: Event name -> params dataclass (spec section 10).\n"
        + "EVENTS: dict[str, type[Any]] = {\n"
        + "\n".join(events)
        + "\n}\n"
    )


def emitters_module() -> str:
    g = Gen(set())
    out = []
    for ev in EVENT_NAMES:
        s = get_def("events.json", ev)
        cls = py_name("events.json", ev)
        props, req = g.collect_props("events.json", s)
        pos, kw, call = [], [], []
        for pname, (pfile, ps) in props.items():
            if pname == "account_id":
                continue
            t, nullable = g.prop_type(pfile, ps)
            if pname in req:
                pos.append(f"{pname}: {qualify(t)}")
            elif not nullable and t == "bool":
                kw.append(f"{pname}: bool = {ps.get('default', False)!r}")
            else:
                kw.append(f"{pname}: {qualify(t)} | None = None")
            call.append(f"{pname}={pname}")
        sig = ", ".join(["self", *pos, "*", *kw, "ack: bool = False"])
        out.append(
            f"    async def {ev.replace('.', '_')}({sig}) -> None:\n"
            f'        """Emit `{ev}` (spec section 10). `ack=True` sends it as a request and waits for the core."""\n'
            f"        await self.emit(T.{cls}(account_id=self.id, {', '.join(call)}), ack=ack)\n"
        )
    return (
        HEADER
        + "from __future__ import annotations\n\n"
        + "from datetime import datetime\nfrom typing import Any\n\n"
        + "from . import types as T\n\n\n"
        + "class EventEmitters:\n"
        + '    """One coroutine per event; mixed into Account."""\n\n'
        + "    id: str\n\n"
        + "    async def emit(self, event: Any, *, ack: bool = False) -> None:  # pragma: no cover\n"
        + "        raise NotImplementedError\n\n"
        + "\n".join(out)
    )


def qualify(t: str) -> str:
    """Prefix generated class names with `T.` inside an annotation string."""
    import re

    builtin = {"str", "int", "float", "bool", "list", "dict", "Any", "None", "datetime"}
    return re.sub(r"\b([A-Z][A-Za-z0-9]*)\b", lambda m: m[1] if m[1] in builtin else f"T.{m[1]}", t)


def main() -> int:
    files = {
        "types.py": types_module(),
        "capabilities.py": capabilities_module(),
        "registry.py": registry_module(),
        "_emitters.py": emitters_module(),
    }
    check = "--check" in sys.argv
    drift = []
    for name, text in files.items():
        p = PKG / name
        if check:
            if not p.exists() or p.read_text() != text:
                drift.append(name)
        else:
            p.write_text(text)
    if drift:
        print("generated modules out of date:", ", ".join(drift), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
